"""
Comprehensive Quality Analysis of C-TVAE Generated Synthetic Data

This script performs rigorous statistical and visual analysis to assess
the quality, realism, and utility of synthetic click data generated by
the Conditional Tabular VAE.

Analyses include:
1. Univariate distribution comparisons
2. Correlation structure preservation
3. Statistical similarity tests
4. Multivariate distribution analysis (PCA)
5. Privacy/uniqueness analysis
6. Domain validity checks
"""

import pickle
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats
from scipy.spatial.distance import jensenshannon
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
import warnings
warnings.filterwarnings('ignore')

# Set style
plt.style.use('seaborn-v0_8-paper')
sns.set_palette("husl")
plt.rcParams['figure.dpi'] = 300
plt.rcParams['savefig.dpi'] = 300

import os
os.makedirs('figures/cvae_quality', exist_ok=True)

print("=" * 80)
print("C-TVAE SYNTHETIC DATA QUALITY ANALYSIS")
print("=" * 80)

# ============================================================================
# 1. LOAD DATA
# ============================================================================
print("\n[1/9] Loading data...")

# Load original training data
with open('train_encoded.pkl', 'rb') as f:
    train_full = pickle.load(f)

# Subsample to 1M (matching what we used for C-TVAE training)
train_data = train_full.sample(n=1_000_000, random_state=42).reset_index(drop=True)

# Ensure label is 0/1
if train_data['label'].min() < 0:
    train_data['label'] = train_data['label'].replace({-1: 0, 1: 1}).astype(int)

# Extract real clicks (what C-TVAE was trained on)
real_clicks = train_data[train_data['label'] == 1].copy()

# Load synthetic data
synthetic_data = pd.read_csv('conditional_tvae_synthetic.csv')

print(f"  Real clicks: {len(real_clicks):,} samples")
print(f"  Synthetic clicks: {len(synthetic_data):,} samples")

# Get numeric features only
numeric_cols = real_clicks.select_dtypes(include=[np.number]).columns.tolist()
if 'label' in numeric_cols:
    numeric_cols.remove('label')

# Ensure same features and they're numeric in both datasets
common_features = [c for c in numeric_cols if c in synthetic_data.columns]
print(f"  Common features (before filtering): {len(common_features)}")

# Double-check: ensure they're actually numeric in both datasets
truly_numeric = []
for col in common_features:
    real_dtype = real_clicks[col].dtype
    synth_dtype = synthetic_data[col].dtype
    if np.issubdtype(real_dtype, np.number) and np.issubdtype(synth_dtype, np.number):
        truly_numeric.append(col)

common_features = truly_numeric
print(f"  Common numeric features (after filtering): {len(common_features)}")

real_clicks_features = real_clicks[common_features].copy()
synthetic_features = synthetic_data[common_features].copy()

# Handle NaN
real_clicks_features = real_clicks_features.fillna(0)
synthetic_features = synthetic_features.fillna(0)

print(f"  Real clicks shape: {real_clicks_features.shape}")
print(f"  Synthetic shape: {synthetic_features.shape}")

# ============================================================================
# 2. UNIVARIATE DISTRIBUTION ANALYSIS
# ============================================================================
print("\n[2/9] Analyzing univariate distributions...")

# Select subset of features for detailed visualization
viz_features = common_features[:12]  # First 12 features

# Create comparison histograms
n_rows = 4
n_cols = 3
fig, axes = plt.subplots(n_rows, n_cols, figsize=(15, 12))
axes = axes.flatten()

for idx, feature in enumerate(viz_features):
    ax = axes[idx]

    real_vals = real_clicks_features[feature].values
    synth_vals = synthetic_features[feature].values

    # Plot distributions
    ax.hist(real_vals, bins=30, alpha=0.6, density=True,
            label='Real', color='blue', edgecolor='black')
    ax.hist(synth_vals, bins=30, alpha=0.6, density=True,
            label='Synthetic', color='red', edgecolor='black')

    # Add mean lines
    ax.axvline(np.mean(real_vals), color='blue', linestyle='--', linewidth=2, alpha=0.8)
    ax.axvline(np.mean(synth_vals), color='red', linestyle='--', linewidth=2, alpha=0.8)

    ax.set_title(f'{feature}', fontsize=9, fontweight='bold')
    ax.set_xlabel('Value', fontsize=8)
    ax.set_ylabel('Density', fontsize=8)
    ax.legend(fontsize=7)
    ax.grid(True, alpha=0.3)
    ax.tick_params(labelsize=7)

plt.suptitle('Univariate Distribution Comparison: Real vs Synthetic\n(First 12 Features)',
             fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figures/cvae_quality/univariate_distributions.png', bbox_inches='tight', dpi=300)
plt.close()
print("  ✓ Univariate distribution plots saved")

# ============================================================================
# 3. STATISTICAL SIMILARITY TESTS
# ============================================================================
print("\n[3/9] Performing statistical similarity tests...")

# Kolmogorov-Smirnov test for each feature
ks_results = []
for feature in common_features:
    real_vals = real_clicks_features[feature].values
    synth_vals = synthetic_features[feature].values

    # KS test
    ks_stat, ks_pval = stats.ks_2samp(real_vals, synth_vals)

    # Jensen-Shannon divergence (for binned distributions)
    real_hist, bin_edges = np.histogram(real_vals, bins=50, density=True)
    synth_hist, _ = np.histogram(synth_vals, bins=bin_edges, density=True)

    # Normalize to probabilities
    real_hist = real_hist / real_hist.sum()
    synth_hist = synth_hist / synth_hist.sum()

    # Add small epsilon to avoid log(0)
    real_hist = real_hist + 1e-10
    synth_hist = synth_hist + 1e-10

    js_div = jensenshannon(real_hist, synth_hist)

    ks_results.append({
        'Feature': feature,
        'KS_Statistic': ks_stat,
        'KS_P_Value': ks_pval,
        'JS_Divergence': js_div,
        'Real_Mean': real_vals.mean(),
        'Synth_Mean': synth_vals.mean(),
        'Real_Std': real_vals.std(),
        'Synth_Std': synth_vals.std()
    })

ks_df = pd.DataFrame(ks_results)

# Summary statistics
print(f"\n  Statistical Test Summary:")
print(f"    Mean KS Statistic: {ks_df['KS_Statistic'].mean():.4f}")
print(f"    Mean JS Divergence: {ks_df['JS_Divergence'].mean():.4f}")
print(f"    Features passing KS test (p > 0.05): {(ks_df['KS_P_Value'] > 0.05).sum()}/{len(ks_df)}")

# Save results
ks_df.to_csv('cvae_statistical_tests.csv', index=False)
print(f"  ✓ Statistical test results saved")

# Visualize KS statistics
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

# KS Statistic distribution
ax = axes[0]
ax.hist(ks_df['KS_Statistic'], bins=30, color='steelblue', alpha=0.7, edgecolor='black')
ax.axvline(ks_df['KS_Statistic'].mean(), color='red', linestyle='--', linewidth=2,
           label=f'Mean: {ks_df["KS_Statistic"].mean():.4f}')
ax.set_xlabel('KS Statistic', fontweight='bold')
ax.set_ylabel('Frequency', fontweight='bold')
ax.set_title('Distribution of KS Statistics Across Features', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)

# JS Divergence distribution
ax = axes[1]
ax.hist(ks_df['JS_Divergence'], bins=30, color='coral', alpha=0.7, edgecolor='black')
ax.axvline(ks_df['JS_Divergence'].mean(), color='red', linestyle='--', linewidth=2,
           label=f'Mean: {ks_df["JS_Divergence"].mean():.4f}')
ax.set_xlabel('Jensen-Shannon Divergence', fontweight='bold')
ax.set_ylabel('Frequency', fontweight='bold')
ax.set_title('Distribution of JS Divergence Across Features', fontweight='bold')
ax.legend()
ax.grid(True, alpha=0.3)

plt.suptitle('Statistical Similarity Measures: Real vs Synthetic Data', fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figures/cvae_quality/statistical_tests.png', bbox_inches='tight', dpi=300)
plt.close()
print("  ✓ Statistical test visualizations saved")

# ============================================================================
# 4. CORRELATION STRUCTURE ANALYSIS
# ============================================================================
print("\n[4/9] Analyzing correlation structure...")

# Select subset of features for correlation analysis (too many to visualize)
corr_features = common_features[:20]  # First 20 features

# Compute correlation matrices
real_corr = real_clicks_features[corr_features].corr()
synth_corr = synthetic_features[corr_features].corr()

# Compute correlation difference
corr_diff = np.abs(real_corr - synth_corr)

# Visualize
fig, axes = plt.subplots(1, 3, figsize=(18, 5))

# Real correlations
ax = axes[0]
sns.heatmap(real_corr, annot=False, cmap='coolwarm', center=0, vmin=-1, vmax=1,
            square=True, linewidths=0.5, cbar_kws={'label': 'Correlation'}, ax=ax)
ax.set_title('Real Data\nCorrelation Matrix', fontweight='bold', fontsize=11)
ax.tick_params(labelsize=7)

# Synthetic correlations
ax = axes[1]
sns.heatmap(synth_corr, annot=False, cmap='coolwarm', center=0, vmin=-1, vmax=1,
            square=True, linewidths=0.5, cbar_kws={'label': 'Correlation'}, ax=ax)
ax.set_title('Synthetic Data\nCorrelation Matrix', fontweight='bold', fontsize=11)
ax.tick_params(labelsize=7)

# Absolute difference
ax = axes[2]
sns.heatmap(corr_diff, annot=False, cmap='Reds', vmin=0, vmax=0.5,
            square=True, linewidths=0.5, cbar_kws={'label': 'Absolute Difference'}, ax=ax)
ax.set_title('Absolute Correlation\nDifference', fontweight='bold', fontsize=11)
ax.tick_params(labelsize=7)

plt.suptitle('Correlation Structure Comparison (First 20 Features)', fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figures/cvae_quality/correlation_comparison.png', bbox_inches='tight', dpi=300)
plt.close()
print("  ✓ Correlation comparison saved")

# Compute correlation preservation metrics
mean_corr_diff = corr_diff.values[np.triu_indices_from(corr_diff.values, k=1)].mean()
print(f"  Mean absolute correlation difference: {mean_corr_diff:.4f}")

# ============================================================================
# 5. MULTIVARIATE ANALYSIS (PCA)
# ============================================================================
print("\n[5/9] Performing multivariate analysis (PCA)...")

# Combine and standardize
combined = pd.concat([
    real_clicks_features.assign(source='Real'),
    synthetic_features.assign(source='Synthetic')
], ignore_index=True)

X_combined = combined[common_features].values
labels = combined['source'].values

# Standardize
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X_combined)

# PCA
pca = PCA(n_components=2)
X_pca = pca.fit_transform(X_scaled)

# Create dataframe for plotting
pca_df = pd.DataFrame({
    'PC1': X_pca[:, 0],
    'PC2': X_pca[:, 1],
    'Source': labels
})

# Visualize
fig, axes = plt.subplots(1, 2, figsize=(14, 6))

# Scatter plot
ax = axes[0]
for source, color in [('Real', 'blue'), ('Synthetic', 'red')]:
    mask = pca_df['Source'] == source
    ax.scatter(pca_df[mask]['PC1'], pca_df[mask]['PC2'],
               alpha=0.3, s=10, color=color, label=source, edgecolors='none')
ax.set_xlabel(f'PC1 ({pca.explained_variance_ratio_[0]*100:.1f}% variance)', fontweight='bold')
ax.set_ylabel(f'PC2 ({pca.explained_variance_ratio_[1]*100:.1f}% variance)', fontweight='bold')
ax.set_title('PCA Projection: Real vs Synthetic Data', fontweight='bold')
ax.legend(frameon=True, shadow=True)
ax.grid(True, alpha=0.3)

# Density plot
ax = axes[1]
for source, color in [('Real', 'blue'), ('Synthetic', 'red')]:
    mask = pca_df['Source'] == source
    ax.hist2d(pca_df[mask]['PC1'], pca_df[mask]['PC2'],
              bins=50, alpha=0.5, cmap='Blues' if source == 'Real' else 'Reds')
ax.set_xlabel(f'PC1 ({pca.explained_variance_ratio_[0]*100:.1f}% variance)', fontweight='bold')
ax.set_ylabel(f'PC2 ({pca.explained_variance_ratio_[1]*100:.1f}% variance)', fontweight='bold')
ax.set_title('PCA Density: Real vs Synthetic Data', fontweight='bold')
ax.grid(True, alpha=0.3)

plt.suptitle('Multivariate Distribution Analysis via PCA', fontsize=13, fontweight='bold')
plt.tight_layout()
plt.savefig('figures/cvae_quality/pca_analysis.png', bbox_inches='tight', dpi=300)
plt.close()
print("  ✓ PCA analysis saved")

# ============================================================================
# 6. FEATURE RANGE VALIDATION
# ============================================================================
print("\n[6/9] Validating feature ranges...")

# Check if synthetic data respects real data ranges
range_violations = []
for feature in common_features:
    real_min = real_clicks_features[feature].min()
    real_max = real_clicks_features[feature].max()
    synth_min = synthetic_features[feature].min()
    synth_max = synthetic_features[feature].max()

    # Check if synthetic values exceed real range
    exceeds_min = synth_min < real_min
    exceeds_max = synth_max > real_max

    if exceeds_min or exceeds_max:
        range_violations.append({
            'Feature': feature,
            'Real_Min': real_min,
            'Real_Max': real_max,
            'Synth_Min': synth_min,
            'Synth_Max': synth_max,
            'Exceeds_Min': exceeds_min,
            'Exceeds_Max': exceeds_max
        })

if len(range_violations) > 0:
    print(f"  ⚠ {len(range_violations)} features have synthetic values outside real range")
    range_df = pd.DataFrame(range_violations)
    range_df.to_csv('cvae_range_violations.csv', index=False)
else:
    print(f"  ✓ All synthetic features within real data range")

# Visualize range comparison
fig, ax = plt.subplots(figsize=(12, 8))

# Select features for visualization
viz_range_features = common_features[:15]
y_pos = np.arange(len(viz_range_features))

for idx, feature in enumerate(viz_range_features):
    real_min = real_clicks_features[feature].min()
    real_max = real_clicks_features[feature].max()
    synth_min = synthetic_features[feature].min()
    synth_max = synthetic_features[feature].max()

    # Plot ranges
    ax.plot([real_min, real_max], [idx, idx], 'b-', linewidth=8, alpha=0.6, label='Real' if idx == 0 else '')
    ax.plot([synth_min, synth_max], [idx-0.2, idx-0.2], 'r-', linewidth=4, alpha=0.8, label='Synthetic' if idx == 0 else '')

ax.set_yticks(y_pos)
ax.set_yticklabels(viz_range_features, fontsize=9)
ax.set_xlabel('Feature Value Range', fontweight='bold')
ax.set_title('Feature Range Comparison: Real vs Synthetic\n(First 15 Features)', fontweight='bold')
ax.legend(loc='best', frameon=True, shadow=True)
ax.grid(True, alpha=0.3, axis='x')

