ax.set_yticklabels(top_std_diff['Feature'], fontsize=8)
ax.set_xlabel('Absolute Std Difference', fontweight='bold')
ax.set_title('Top 15 Features by Std Difference', fontweight='bold')
ax.grid(True, alpha=0.3, axis='x')

plt.suptitle('Summary Statistics Differences: Real vs Synthetic', fontsize=13, fontweight='bold')
plt.tight_layout()
