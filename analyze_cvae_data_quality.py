# ============================================================================
# 7. PRIVACY ANALYSIS (UNIQUENESS)
# ============================================================================
print("\n[7/9] Analyzing privacy/uniqueness...")

# Check if synthetic samples are simply copies of real samples
# Use a subset of features for matching
match_features = common_features[:10]

# Round to avoid floating point precision issues
real_rounded = real_clicks_features[match_features].round(4)
synth_rounded = synthetic_features[match_features].round(4)

# Check for exact matches
n_exact_matches = 0
for idx in range(min(1000, len(synth_rounded))):  # Check first 1000 synthetic samples
    synth_row = synth_rounded.iloc[idx]
    # Check if this row exists in real data
    matches = (real_rounded == synth_row).all(axis=1).sum()
    if matches > 0:
        n_exact_matches += 1

exact_match_rate = n_exact_matches / min(1000, len(synth_rounded)) * 100

print(f"  Exact match rate (first 1000 samples): {exact_match_rate:.2f}%")
if exact_match_rate < 5:
    print(f"  ✓ Low exact match rate - synthetic data is novel")
else:
    print(f"  ⚠ High exact match rate - may be copying real data")

# Compute nearest neighbor distances
from scipy.spatial.distance import cdist

# Sample for computational efficiency
sample_size = 500
real_sample = real_clicks_features[match_features].sample(n=min(sample_size, len(real_clicks_features)), random_state=42).values
synth_sample = synthetic_features[match_features].sample(n=min(sample_size, len(synthetic_features)), random_state=42).values

# Compute pairwise distances
distances = cdist(synth_sample, real_sample, metric='euclidean')
min_distances = distances.min(axis=1)

print(f"  Mean nearest neighbor distance: {min_distances.mean():.4f}")
print(f"  Median nearest neighbor distance: {np.median(min_distances):.4f}")

